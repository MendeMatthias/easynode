/// The `miner` preset faststart.conf (minus the `addnode=` lines, which
/// `ensure_addnodes_in_conf` appends right after provisioning).
///
/// `prune=0` (NOT the legacy python preset's `prune=4096`) is DELIBERATE and the
/// fix for the "restart → full re-sync" bug: on a PRUNED node, an unclean btxd
/// shutdown (OS restart, lid close, force-quit, power loss) leaves the shielded-
/// state DB needing a rebuild that reads HISTORICAL blocks — which pruning deleted
/// (`ReadRawBlock: OpenBlockFile failed nFile=-1`) → "Failed to initialize shielded
/// state database" → btxd won't start → the app's repair wipes the chain → hours of
/// re-sync. Keeping every block (prune=0) means the shielded rebuild always has its
/// blocks, so a restart just RESUMES. assumeutxo still fast-starts (snapshot → mine
/// at the base height) while the full chain backfills in the background; it just
/// KEEPS the blocks instead of deleting them. Costs more disk, buys restart-safety.
pub const MINER_FASTSTART_CONF: &str = "\
# Generated by EasyBTX (self-contained native faststart)
# Preset: miner
server=1
listen=1
rpcbind=127.0.0.1
rpcallowip=127.0.0.1
# prune=0 keeps ALL blocks so btxd can rebuild shielded state after an unclean
# shutdown. A pruned node CANNOT (it deleted the blocks the rebuild needs), which
# turns every hard restart into a multi-hour re-sync. Do not re-enable pruning.
# blockfilterindex/coinstatsindex are intentionally OFF: EasyBTX never queries
# them (no gettxoutsetinfo/getblockfilter caller), and on an un-pruned node they
# add GBs of dead index. disk::reclaim_disk strips them from older installs too.
prune=0
retainshieldedcommitmentindex=1
miningminoutboundpeers=2
miningminsyncedoutboundpeers=1
miningmaxheaderlag=8
";

/// The `node` preset faststart.conf for the standalone easyBTX Node app: the
/// miner preset minus the three `mining*` chain-guard tuning keys (the node app
/// never mines, so btxd's defaults are right). Everything else is identical —
/// especially `prune=0`, which keeps restarts safe (see the miner-conf comment
/// above), and localhost-only RPC.
pub const NODE_FASTSTART_CONF: &str = "\
# Generated by easyBTX Node (self-contained native faststart)
# Preset: node
server=1
listen=1
rpcbind=127.0.0.1
rpcallowip=127.0.0.1
# prune=0 keeps ALL blocks so btxd can rebuild shielded state after an unclean
# shutdown. A pruned node CANNOT (it deleted the blocks the rebuild needs), which
# turns every hard restart into a multi-hour re-sync. Do not re-enable pruning.
prune=0
retainshieldedcommitmentindex=1
# Deep-reorg protection. btxd ships this DISABLED in every built-in profile, so
# without these lines a node follows whichever branch carries the most chainwork.
# During the 2026-08-11 split that was the WRONG one: a competing branch forked
# at 185544 and ran longer in headers (186234 against the canonical 186011), so
# following chainwork alone meant a ~464-block reorg onto a chain whose blocks
# the rest of the network does not count.
#
# Parking at depth 6 makes the node refuse to auto-switch that far and hold its
# tip instead. That is the safe direction: a node that stops is recoverable and
# visible, a node that silently reorganises onto a dead branch looks perfectly
# healthy while being useless. Depths follow the BTX team's own guidance issued
# during the incident.
#
# ⚠ This protects a node going FORWARD. It does NOT rescue one already sunk on a
# stale branch — chainwork keeps those locked, and recovery needs
# `invalidateblock` plus blocks from a known-good peer.
parkdeepreorg=1
maxreorgdepthpark=6
maxreorgdepthwarn=3
";

/// The KEEPER preset: a small pruned node whose job is serving signed
/// confirmations (attestations) — the visual, one-click version of keeper/.
///
/// ⚠ ENGINE-GATED. This conf is only safe on a bundled btxd that contains
/// BOTH upstream fixes:
///   - `1d73e70b` — rebuild_from_chain refuses the genesis wipe when
///     ahead-of-snapshot blocks are missing (without it, pruned + snapshot +
///     one unclean shutdown = the bricked-datadir scar `prune=0` exists for);
///   - `0ece8ef4` — trusted mirrors may serve GETMMATTEST (without it a
///     keeper ADVERTISES the archive bit and answers nothing — the exact
///     network-wide bug the 2026-08-17 census decomposed).
/// The pin has MOVED since this warning was written. It is `v0.34.5`, which the
/// denylist in `engine_supports_keeper_profile` does not name, so this conf
/// ships to keepers today — the opposite of what this comment used to say in
/// the present tense ("the pinned 1e51f0d1 predates both"). Note carefully what
/// that admission is and is not: it is a denylist DEFAULT, not a positive
/// verification that v0.34.5 contains `1d73e70b` and `0ece8ef4`. Nothing in
/// this repository checks that. Callers select this conf through
/// `conf_for_profile`, which applies the gate; never pass it directly.
pub const NODE_KEEPER_CONF: &str = "\
# Generated by easyBTX Node (self-contained native faststart)
# Preset: keeper — pruned, serves signed confirmations
server=1
listen=1
rpcbind=127.0.0.1
rpcallowip=127.0.0.1
# Keeper keeps ~10 GB of recent blocks, not the whole chain. Safe ONLY on an
# engine with the pruned-snapshot rebuild fix (see the gate in installer.rs).
prune=10000
retainshieldedcommitmentindex=1
# Serve signed confirmations — the point of the profile.
matmulattestationserve=1
# Deep-reorg protection: same posture as the full-node preset (2026-08-11 split).
parkdeepreorg=1
maxreorgdepthpark=6
maxreorgdepthwarn=3
";

/// Does the bundled node engine support the keeper profile? Keyed on the
/// node release TAG the app pins (`commands.rs::NODE_RELEASE_TAG`), because
/// the tag is the one identity the app controls end to end.
///
/// TODAY IT ANSWERS YES. The pin is `v0.34.5`, which is not in the denylist
/// below, so keepers get the pruned conf. This doc previously said the shipped
/// engine answers NO, which was true of `v0.33.3-pr105b` and stopped being true
/// when the pin moved — and nothing failed, because nothing asserted it. See
/// `the_shipped_pin_makes_a_deliberate_keeper_decision` in the node app, which
/// forces the next pin bump to make this choice consciously rather than
/// inherit whatever the denylist happens to default to.
///
/// READ THE BODY BEFORE RELYING ON THIS. It is a DENYLIST, not an allowlist and
/// not a version comparison. The four tags named below are the engines known to
/// PREDATE the two fixes. EVERY other string returns true, including a tag this
/// app has never heard of.
///
/// For real engines that is the intended answer: anything cut after `v0.33.3`
/// contains both fixes, so defaulting unknown-newer to yes is correct and means
/// a future pin bump does not have to remember to edit this function.
///
/// The cost is that a WRONG tag also returns true. Verified by evaluating both
/// `matches!` arms: `"v0.34.9-typo"`, `"V0.33.2"` (wrong case) and `""` all
/// answer yes, because none of them is spelled like one of the four denied
/// tags. So this gate is not a defence against a garbled or mistaken tag. It
/// defends against exactly the four old engines it names and nothing else. If
/// the pin is ever set to a string that does not correspond to a real release,
/// a keeper conf goes out on whatever engine is actually installed.
///
/// The first `matches!` arm is redundant: `v0.33.3-pr105c` and `v0.33.3` are
/// absent from the denylist, so the second arm already admits them. It is kept
/// as a record of the first blessed tags, not as the thing doing the work.
pub fn engine_supports_keeper_profile(node_release_tag: &str) -> bool {
    // v0.33.3-pr105c (btxd 1932613f + anchor memo) is the first blessed tag:
    // it contains 1d73e70b and 0ece8ef4, the two fixes the gate exists for.
    matches!(node_release_tag, "v0.33.3-pr105c" | "v0.33.3")
        || !matches!(
            node_release_tag,
            "v0.33.3-pr105b" | "v0.33.2" | "v0.33.1" | "v0.33.0"
        )
}

/// Select the faststart conf for a profile, applying the engine gate. A keeper
/// CHOICE on one of the four denied engines provisions the safe full-node conf
/// instead, and the UI tells the user their choice activates with the next
/// engine update.
///
/// The strength of that gate is the strength of `engine_supports_keeper_profile`,
/// which is a denylist. Every tag outside those four gets the keeper conf, so
/// this function screens out the known-old engines. It does not verify that the
/// installed engine is a real release, and a mistyped pin passes.
pub fn conf_for_profile(profile: &str, node_release_tag: &str) -> &'static str {
    if profile == "keeper" && engine_supports_keeper_profile(node_release_tag) {
        NODE_KEEPER_CONF
    } else {
        NODE_FASTSTART_CONF
    }
}

/// Resolve the directory holding the bundled node binaries (`resources/node-bin/`).
/// In a packaged app Tauri copies `resources/node-bin/*` under the resource dir;
/// in `tauri dev` we fall back to the consuming APP's own `resources/node-bin/`
/// (passed via `dev_roots`, typically `&[Path::new(env!("CARGO_MANIFEST_DIR"))]`
/// evaluated in the app crate — btx-core is a library and has no resources of
/// its own). Returns `None` (so the caller falls back to the python installer)
/// when no `btxd` is found in any candidate — e.g. a build that didn't bundle
/// the binaries.
pub fn resolve_bundled_node_bin(
    resource_dir: Option<&Path>,
    dev_roots: &[&Path],
) -> Option<PathBuf> {
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Some(res) = resource_dir {
        // Tauri's resource layout differs across versions/platforms: some place
        // declared `resources/node-bin/*` directly under the resource dir, others
        // preserve the leading `resources/`. Check BOTH so a real bundle never
        // silently falls back to the python installer (which can't run on a clean
        // Mac). This mirrors the two conventions already seen in this codebase
        // (resolve_faststart_script vs resolve_solver_bin).
        candidates.push(res.join("node-bin"));
        candidates.push(res.join("resources").join("node-bin"));
    }
    for root in dev_roots {
        candidates.push(root.join("resources").join("node-bin"));
    }
    // The daemon's filename carries the platform exe suffix (btxd vs btxd.exe).
    // Probing the bare "btxd" silently misses a real Windows bundle and falls
    // back to the (mac-only) python installer — so resolve via exe_name().
    let btxd_name = crate::platform::exe_name("btxd");
    candidates.into_iter().find(|p| p.join(&btxd_name).exists())
}

/// Self-contained, dependency-free provisioning: copy the bundled node binaries
/// into the deterministic install dir, make them executable + ad-hoc sign them
/// (so macOS doesn't SIGKILL an unsigned Mach-O), and write the miner conf.
///
/// This produces the SAME `FaststartResult` the python installer would, so the
/// rest of `first_run_setup` (node start, `ensure_snapshot_loaded`, mining) is
/// unchanged — but with NO runtime dependency on system `python3` or `gpg`. Trust
/// comes from the binaries shipping INSIDE the distributed app, not a runtime
/// download + GPG check.
pub fn provision_from_bundle(
    bundled_bin_dir: &Path,
    release_tag: &str,
    datadir: &Path,
) -> AppResult<FaststartResult> {
    let install_bin = install_dir(release_tag)
        .ok_or_else(|| AppError::Config("HOME unset; cannot resolve install dir".into()))?
        .join("bin");
    std::fs::create_dir_all(&install_bin).map_err(|e| {
        AppError::Process(format!("create install dir {}: {e}", install_bin.display()))
    })?;

    for name in BUNDLED_NODE_BINARIES {
        // Bundled filenames carry the platform exe suffix (btxd vs btxd.exe), so
        // resolve both the source and destination through exe_name().
        let fname = crate::platform::exe_name(name);
        let src = bundled_bin_dir.join(&fname);
        if !src.exists() {
            if *name == "btxd" || *name == "btx-cli" {
                return Err(AppError::Config(format!(
                    "bundled binary missing: {fname} (looked in {})",
                    bundled_bin_dir.display()
                )));
            }
            // Best-effort tool — skip it.
            continue;
        }
        let dst = install_bin.join(&fname);
        std::fs::copy(&src, &dst).map_err(|e| AppError::Process(format!("copy {fname}: {e}")))?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let _ = std::fs::set_permissions(&dst, std::fs::Permissions::from_mode(0o755));
        }
        // Re-sign on THIS machine so the kernel accepts the exec (matches what the
        // python installer + NodeController do for downloaded binaries).
        crate::node::ensure_adhoc_signed(&dst, datadir);
    }

    // Write the miner faststart.conf (bootstrap peers appended by the caller).
    let faststart_dir = datadir.join("faststart");
    std::fs::create_dir_all(&faststart_dir)
        .map_err(|e| AppError::Process(format!("create faststart dir: {e}")))?;
    let conf_path = faststart_dir.join("faststart.conf");
    std::fs::write(&conf_path, MINER_FASTSTART_CONF)
        .map_err(|e| AppError::Process(format!("write faststart.conf: {e}")))?;

    Ok(FaststartResult {
        btxd: install_bin.join(crate::platform::exe_name("btxd")),
        btx_cli: install_bin.join(crate::platform::exe_name("btx-cli")),
        faststart_conf: conf_path,
        mining_results_dir: None,
    })
}

/// Absolute install directory a given `release_tag`'s binaries live under:
/// `~/.local/btx/<release_tag>/<platform_id>/`. Returns `None` if `$HOME` is
/// unset. Mirrors `returning_launch_paths`' layout so the Settings panel can
/// size the install on disk.
pub fn install_dir(release_tag: &str) -> Option<PathBuf> {
    let home = crate::platform::home_dir()?;
    Some(
        home.join(".local")
            .join("btx")
            .join(release_tag)
            .join(platform_id()),
    )
}

/// Platform id string matching `btx-agent-setup.py`'s `detect_platform_id`.
pub fn platform_id() -> &'static str {
    #[cfg(all(target_os = "macos", target_arch = "aarch64"))]
    {
        "macos-arm64"
    }
    #[cfg(all(target_os = "macos", target_arch = "x86_64"))]
    {
        "macos-x86_64"
    }
    #[cfg(all(target_os = "linux", target_arch = "x86_64"))]
    {
        "linux-x86_64"
    }
    #[cfg(all(target_os = "linux", target_arch = "aarch64"))]
    {
        "linux-arm64"
    }
    #[cfg(all(target_os = "windows", target_arch = "x86_64"))]
    {
        "windows-x86_64"
    }
    #[cfg(not(any(
        all(target_os = "macos", target_arch = "aarch64"),
        all(target_os = "macos", target_arch = "x86_64"),
        all(target_os = "linux", target_arch = "x86_64"),
        all(target_os = "linux", target_arch = "aarch64"),
        all(target_os = "windows", target_arch = "x86_64"),
    )))]
    {
        "unknown"
    }
}

/// Recursively find the first file named `name` under `dir` (mirrors the
/// installer's `find_binary` rglob+sorted behaviour). Shallow, dependency-free
/// walk; returns the lexicographically-first match for determinism.
fn find_binary(dir: &Path, name: &str) -> Option<PathBuf> {
    let mut matches: Vec<PathBuf> = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        // Skip unreadable directories rather than aborting the whole walk.
        let Ok(entries) = std::fs::read_dir(&d) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.file_name().and_then(|n| n.to_str()) == Some(name) {
                matches.push(path);
            }
        }
    }
    matches.sort();
    matches.into_iter().next()
}

/// Resolve the absolute path to the bundled `btx-agent-setup.py`.
///
/// Resolution order (first existing wins):
///   1. **Bundled app** — `<resource_dir>/faststart/btx-agent-setup.py`.
///      Tauri copies `resources/faststart/*` next to the binary, and
///      `resource_dir` points at that location in a packaged build.
///   2. **`tauri dev`** — `resource_dir` is unreliable in dev, so fall back to
///      the crate's own `resources/faststart/` via `CARGO_MANIFEST_DIR` (baked
///      in at compile time = `src-tauri/`).
///   3. **Repo source** — the upstream `contrib/faststart/` copy, as a last
///      resort for running from a checkout without a bundled resource.
///
/// The bundled `btx-agent-setup.py` execs `btx-faststart.py` from its own
/// directory (`SCRIPT_DIR / "btx-faststart.py"`), so as long as both scripts
/// live in the SAME resolved directory the sibling exec just works.
pub fn resolve_faststart_script(
    resource_dir: Option<&Path>,
    dev_roots: &[&Path],
) -> AppResult<PathBuf> {
    let mut candidates: Vec<PathBuf> = Vec::new();

    // 1. Bundled resource dir (packaged app).
    if let Some(res) = resource_dir {
        candidates.push(res.join("faststart").join(FASTSTART_ENTRY_SCRIPT));
    }
    // 2. Dev: the consuming APP's resources dir (its CARGO_MANIFEST_DIR — the
    //    env! macro must be evaluated in the app crate, not in this library).
    for root in dev_roots {
        candidates.push(
            root.join("resources")
                .join("faststart")
                .join(FASTSTART_ENTRY_SCRIPT),
        );
        // 3. Repo source checkout (sibling btx-main at the workspace root).
        if let Some(repo_parent) = root.parent().and_then(|p| p.parent()) {
            candidates.push(
                repo_parent
                    .join("btx-main")
                    .join("contrib")
                    .join("faststart")
                    .join(FASTSTART_ENTRY_SCRIPT),
            );
        }
    }

    candidates
        .iter()
        .find(|p| p.exists())
        .cloned()
        .ok_or_else(|| {
            AppError::Config(format!(
                "could not locate bundled {FASTSTART_ENTRY_SCRIPT}; looked in: {}",
                candidates
                    .iter()
                    .map(|p| p.display().to_string())
                    .collect::<Vec<_>>()
                    .join(", ")
            ))
        })
}

/// Import the bundled BTX release public key into the process-local gpg keyring.
///
/// This must be called BEFORE `run_faststart` so that `gpg --verify` inside the
/// installer subprocess can find the key. `gpg --import` is idempotent: re-importing
/// an already-present key exits 0, so calling this on every first-run is safe.
pub fn import_release_key(
    runner: &dyn CommandRunner,
    gpg_bin: &str,
    key_path: &Path,
) -> AppResult<()> {
    let out = runner
        .run(
            gpg_bin,
            &["--import".to_string(), key_path.display().to_string()],
            &[],
        )
        .map_err(|_| {
            AppError::Config(
                "GnuPG (gpg) is required to verify the BTX release. \
                 Install it (e.g. 'brew install gnupg') and retry."
                    .to_string(),
            )
        })?;

    if !out.status.success() {
        return Err(AppError::Process(format!(
            "gpg --import failed: {}",
            String::from_utf8_lossy(&out.stderr)
        )));
    }

    Ok(())
}

