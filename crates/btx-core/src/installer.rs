/// Entry-point installer script bundled under `resources/faststart/`.
pub const FASTSTART_ENTRY_SCRIPT: &str = "btx-agent-setup.py";

#[derive(Debug, Clone, PartialEq)]
pub struct FaststartResult {
    pub btxd: PathBuf,
    pub btx_cli: PathBuf,
    pub faststart_conf: PathBuf,
    pub mining_results_dir: Option<PathBuf>,
}

/// Reconstruct the install paths a *returning* user already has on disk,
/// WITHOUT re-running the (network-bound, multi-second) faststart installer.
///
/// `btx-agent-setup.py` installs binaries to a deterministic location:
/// `~/.local/btx/<release_tag>/<platform_id>/` (recursively containing `btxd`
/// and `btx-cli`), and `btx-faststart.py` writes the node config to
/// `<datadir>/faststart/faststart.conf`. We mirror that convention here so the
/// returning-user path can start the node directly. Returns `None` if the
/// expected binaries can't be found (e.g. a partially-removed install), so the
/// caller can fall back to a full re-install.
pub fn returning_launch_paths(datadir: &Path, release_tag: &str) -> Option<FaststartResult> {
    let home = crate::platform::home_dir()?;
    let install_dir = home
        .join(".local")
        .join("btx")
        .join(release_tag)
        .join(platform_id());

    let btxd = find_binary(&install_dir, &crate::platform::exe_name("btxd"))?;
    let btx_cli = find_binary(&install_dir, &crate::platform::exe_name("btx-cli"))?;
    let faststart_conf = datadir.join("faststart").join("faststart.conf");
    let mining_results_dir = {
        let d = datadir.join("mining-ops");
        d.exists().then_some(d)
    };

    Some(FaststartResult {
        btxd,
        btx_cli,
        faststart_conf,
        mining_results_dir,
    })
}

