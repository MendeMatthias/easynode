/// v0.33.3 (the 191,714 ASERT-dump-floor hard fork, published 2026-08-17T15:19Z
/// from commit 6053ef71) is a native cut whose release notes state outright that
/// it is not GPG-signed and that `btx-agent-setup.py` needs
/// `--allow-unsigned-release`. Passing that flag alone would shift trust to the
/// channel-served SHA256SUMS; these compiled-in digests are the compensating
/// control. They were measured 2026-08-17 from the release API AND re-verified
/// by downloading the assets and hashing them locally; the installer script
