    /// Build a fake v0.32.12-style package tree: script wrappers in bin/, a
    /// fake Mach-O daemon in libexec/, and a metal shader dir that must be
    /// copied verbatim but never chmodded/signed.
    fn fake_node_pkg(root: &Path) {
        std::fs::create_dir_all(root.join("bin")).unwrap();
        std::fs::create_dir_all(root.join("libexec").join("metal")).unwrap();
        // Wrapper filenames carry the platform exe suffix (btxd vs btxd.exe) —
        // provision_node_package probes via exe_name(), so the fixture must too
        // or the test only passes on unix.
        std::fs::write(
            root.join("bin").join(crate::platform::exe_name("btxd")),
            b"#!/bin/sh\nexec real\n",
        )
        .unwrap();
        std::fs::write(
            root.join("bin").join(crate::platform::exe_name("btx-cli")),
            b"#!/bin/sh\nexec real\n",
        )
        .unwrap();
        // 64-bit little-endian Mach-O magic on disk reads big-endian as cf fa ed fe.
        let mut macho = vec![0xcfu8, 0xfa, 0xed, 0xfe];
        macho.extend_from_slice(&[0u8; 64]);
        std::fs::write(root.join("libexec").join("btxd.real"), &macho).unwrap();
        std::fs::write(
            root.join("libexec").join("metal").join("kernels.metallib"),
            b"shaders",
        )
        .unwrap();
    }

