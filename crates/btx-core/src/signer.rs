/// The key file, inside the datadir. The same name this project's validator
/// has used since 2026-09-01, so that machine's existing key is adopted rather
/// than replaced when it updates.
pub const SIGNER_KEY_FILE: &str = "attestation-signer.key";

/// The engine option the file is handed to. A relative value resolves under
/// the network datadir, which for mainnet is the datadir itself.
pub const SIGNER_KEY_CONF_KEY: &str = "matmulattestationsignerkeyfile";

/// BTX's WIF version byte. Read from the validator's key (2026-09-16) and
/// proven against the engine, see the module doc.
pub const BTX_WIF_VERSION: u8 = 0x99;

/// How many recent blocks the "is it working" line looks at.
pub const SIGNED_WINDOW_BLOCKS: u64 = 100;

/// The trusted mirrors this project's signers feed. A signer dials them as
/// manual peers so its attestations arrive over a direct connection (see the
