/// The signing key on disk, described without its secret.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SignerKey {
    pub path: PathBuf,
    /// 66 lowercase hex characters: the compressed secp256k1 public key, the
    /// form the engine lists in `trusted_signer_pubkeys` and the form a mirror
    /// pins with `matmultrustedpubkey=`.
    pub pubkey_hex: String,
    /// True when this call generated the key; false when it read one that was
    /// already there.
    pub created: bool,
}

/// Where the key lives for a datadir.
pub fn signer_key_path(datadir: &Path) -> PathBuf {
    datadir.join(SIGNER_KEY_FILE)
}

/// A fresh WIF for BTX: version 0x99, a 32-byte secret the curve accepts, the
/// compressed-key flag, base58check.
///
/// The secret comes from the operating system's CSPRNG. A byte string outside
/// the curve order is rejected by `SecretKey::from_slice` and drawn again; the
/// probability is about 2^-128 per draw, so the loop is a formality that keeps
/// the function total.
pub fn generate_wif() -> String {
    use rand_core::RngCore as _;
    loop {
        let mut bytes = [0u8; 32];
        rand_core::OsRng.fill_bytes(&mut bytes);
        if k256::SecretKey::from_slice(&bytes).is_ok() {
            return wif_from_secret(&bytes);
        }
    }
}

fn wif_from_secret(secret: &[u8; 32]) -> String {
    let mut payload = Vec::with_capacity(34);
    payload.push(BTX_WIF_VERSION);
    payload.extend_from_slice(secret);
    payload.push(0x01); // compressed public key
    bs58::encode(payload).with_check().into_string()
}

/// The compressed public key a WIF signs as, as 66 lowercase hex characters.
///
/// Refuses anything that is not a BTX compressed WIF: wrong checksum, wrong
/// version byte, uncompressed form. The engine would refuse those too, at
/// init, with the node down; better to say so here while it is still up.
pub fn wif_to_pubkey_hex(wif: &str) -> AppResult<String> {
    let payload = bs58::decode(wif.trim())
        .with_check(None)
        .into_vec()
        .map_err(|e| AppError::Config(format!("signing key is not valid base58check: {e}")))?;
    if payload.len() != 34 {
        return Err(AppError::Config(format!(
            "signing key has {} payload bytes; a compressed WIF has 34",
            payload.len()
        )));
    }
    if payload[0] != BTX_WIF_VERSION {
        return Err(AppError::Config(format!(
            "signing key version byte is 0x{:02x}; BTX keys use 0x{:02x}",
            payload[0], BTX_WIF_VERSION
        )));
    }
    if payload[33] != 0x01 {
        return Err(AppError::Config(
            "signing key is not marked compressed; the engine pins compressed keys".to_string(),
        ));
    }
    let sk = k256::SecretKey::from_slice(&payload[1..33])
        .map_err(|_| AppError::Config("signing key secret is not on the curve".to_string()))?;
    let point = sk.public_key().to_encoded_point(true);
    Ok(hex_lower(point.as_bytes()))
}

fn hex_lower(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

/// Make sure the datadir holds a usable signing key, generating one only when
/// there is none.
///
/// An existing file is never overwritten, even when it does not parse: a key
/// file is the one thing in the datadir the app did not necessarily write (the
/// validator's was made by hand), and replacing it would silently retire a
/// key that mirrors pin. An unparseable file is an error the caller shows.
///
/// The file is created `0600` on Unix and written whole under a temporary
/// name before it takes its final name, so a crash mid-write leaves either no
/// key or a complete one. It holds one line: the WIF and a newline.
pub fn ensure_signer_key(datadir: &Path) -> AppResult<SignerKey> {
    let path = signer_key_path(datadir);
    if path.exists() {
        let wif = std::fs::read_to_string(&path).map_err(|e| {
            AppError::Config(format!("cannot read signing key {}: {e}", path.display()))
        })?;
        let pubkey_hex = wif_to_pubkey_hex(&wif)
            .map_err(|e| AppError::Config(format!("{}: {e}", path.display())))?;
        return Ok(SignerKey {
            path,
            pubkey_hex,
            created: false,
        });
    }
    std::fs::create_dir_all(datadir)
        .map_err(|e| AppError::Config(format!("cannot create {}: {e}", datadir.display())))?;
    let wif = generate_wif();
    let pubkey_hex = wif_to_pubkey_hex(&wif).expect("a key this module generated parses");
    write_private(&path, format!("{wif}\n").as_bytes())?;
    Ok(SignerKey {
        path,
        pubkey_hex,
        created: true,
    })
}

/// The public key of the key on disk, or `None` when there is no readable key.
/// For display: the status poll asks this and must not fail on a missing file.
pub fn read_signer_pubkey(datadir: &Path) -> Option<String> {
    let wif = std::fs::read_to_string(signer_key_path(datadir)).ok()?;
    wif_to_pubkey_hex(&wif).ok()
}

/// Write a secret: owner-only permissions from the first byte, and atomic.
fn write_private(path: &Path, bytes: &[u8]) -> AppResult<()> {
    use std::io::Write as _;
    let tmp = path.with_extension(format!("key.tmp-{}", std::process::id()));
    let mut opts = std::fs::OpenOptions::new();
    opts.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        opts.mode(0o600);
    }
    let result = (|| -> std::io::Result<()> {
        let mut f = opts.open(&tmp)?;
        f.write_all(bytes)?;
        f.sync_all()?;
        std::fs::rename(&tmp, path)
    })();
    if let Err(e) = result {
        let _ = std::fs::remove_file(&tmp);
        return Err(AppError::Config(format!(
            "cannot write signing key {}: {e}",
            path.display()
        )));
    }
    Ok(())
}

/// Every signer public key an attestation carries.
///
/// The attestation wire format is the engine's and is not documented here;
/// what is stable, and what this reads, is the signature field: a
/// length-prefixed compressed public key (`21` then `02`/`03` and 32 bytes)
/// immediately followed by a length-prefixed DER signature (`44`..`48`, then
/// the `30` sequence tag). Measured on a version-2 attestation from this
/// project's validator at height 221,524 on 2026-09-16, and pinned by a test.
/// Any other 66-hex run in the attestation (hashes, the replay context) fails
/// the prefix-and-suffix shape and is not a key.
pub fn attestation_signer_pubkeys(attestation_hex: &str) -> Vec<String> {
    let h = attestation_hex.trim().to_ascii_lowercase();
    let b = h.as_bytes();
    let mut out = Vec::new();
    // Byte-aligned scan: the hex string is a byte string, so a field can only
    // start at an even offset.
    let mut i = 0;
    while i + 2 + 66 + 4 <= b.len() {
        if &b[i..i + 2] == b"21"
            && (&b[i + 2..i + 4] == b"02" || &b[i + 2..i + 4] == b"03")
            && b[i + 4..i + 68].iter().all(|c| c.is_ascii_hexdigit())
        {
            let sig_len = &b[i + 68..i + 70];
            let der_tag = &b[i + 70..i + 72];
            if matches!(sig_len, b"44" | b"45" | b"46" | b"47" | b"48") && der_tag == b"30" {
                let key = h[i + 2..i + 68].to_string();
                if !out.contains(&key) {
                    out.push(key);
                }
                i += 68;
                continue;
            }
        }
        i += 2;
    }
    out
}

/// A rolling window over the newest blocks: who signed each one.
///
/// Pure. Fed by [`refresh_recent_signers`] on a live node and by tests
/// directly. Holds at most [`SIGNED_WINDOW_BLOCKS`] heights; a height recorded
/// twice (a reorg replaced the block, or the newest block gained a signature
/// after it was first read) replaces the earlier entry.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RecentSigners {
    /// Oldest first. `(height, hash, signer pubkeys)`.
    entries: VecDeque<(u64, String, Vec<String>)>,
}

/// What the window says, for a person or for the census.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct RecentSignersSummary {
    /// Blocks looked at: the window's target size.
    pub window: u64,
    /// Blocks actually read so far (fewer than `window` right after a start).
    pub seen: u64,
    /// The newest height in the window, or 0 when empty.
    pub tip: u64,
    /// Blocks in the window that carry at least one signature.
    pub blocks_with_signature: u64,
    /// Distinct public keys seen across the window.
    pub distinct_keys: u64,
    /// Blocks signed, per public key.
    pub keys: BTreeMap<String, u64>,
}

impl RecentSigners {
    pub fn new() -> Self {
        Self::default()
    }

    /// Record the signers of one block. Heights arrive in any order; the
    /// window keeps the newest `SIGNED_WINDOW_BLOCKS` of them.
    pub fn record(&mut self, height: u64, hash: &str, attestation_hexes: &[String]) {
        let mut keys: Vec<String> = Vec::new();
        for a in attestation_hexes {
            for k in attestation_signer_pubkeys(a) {
                if !keys.contains(&k) {
                    keys.push(k);
                }
            }
        }
        self.entries.retain(|(h, _, _)| *h != height);
        let pos = self.entries.partition_point(|(h, _, _)| *h < height);
        self.entries.insert(pos, (height, hash.to_string(), keys));
        while self.entries.len() as u64 > SIGNED_WINDOW_BLOCKS {
            self.entries.pop_front();
        }
    }

    /// The newest height recorded, if any.
    pub fn highest(&self) -> Option<u64> {
        self.entries.back().map(|(h, _, _)| *h)
    }

    /// The hash recorded at a height, if that height is in the window.
    pub fn hash_at(&self, height: u64) -> Option<&str> {
        self.entries
            .iter()
            .find(|(h, _, _)| *h == height)
            .map(|(_, hash, _)| hash.as_str())
    }

    /// Which heights to read next so the window covers the `SIGNED_WINDOW_BLOCKS`
    /// blocks up to `tip`, oldest first, at most `budget` of them.
    ///
    /// Entries below the window's floor are dropped first, so a node that was
    /// stopped for a day does not keep yesterday's heights. The newest recorded
    /// height is included again: the block at the tip is often read before its
    /// signature is stored, and a reorg can replace it, so it is always worth
    /// one more look (its cost is two RPCs).
    pub fn heights_to_read(&mut self, tip: u64, budget: usize) -> Vec<u64> {
        let floor = tip.saturating_sub(SIGNED_WINDOW_BLOCKS - 1);
        self.entries.retain(|(h, _, _)| *h >= floor && *h <= tip);
        let mut out = Vec::new();
        let mut h = floor;
        while h <= tip && out.len() < budget {
            let known = self.entries.iter().any(|(k, _, _)| *k == h);
            if !known || h == tip || Some(h) == self.highest() {
                out.push(h);
            }
            h += 1;
        }
        out
    }

    pub fn summary(&self) -> RecentSignersSummary {
        let mut keys: BTreeMap<String, u64> = BTreeMap::new();
        let mut with_sig = 0u64;
        for (_, _, ks) in &self.entries {
            if !ks.is_empty() {
                with_sig += 1;
            }
            for k in ks {
                *keys.entry(k.clone()).or_insert(0) += 1;
            }
        }
        RecentSignersSummary {
            window: SIGNED_WINDOW_BLOCKS,
            seen: self.entries.len() as u64,
            tip: self.highest().unwrap_or(0),
            blocks_with_signature: with_sig,
            distinct_keys: keys.len() as u64,
            keys,
        }
    }

    /// How many blocks in the window carry `pubkey_hex`, with how many were
    /// looked at.
    pub fn signed_by(&self, pubkey_hex: &str) -> SignedRecent {
        let want = pubkey_hex.to_ascii_lowercase();
        SignedRecent {
            signed: self
                .entries
                .iter()
                .filter(|(_, _, ks)| ks.contains(&want))
                .count() as u64,
            seen: self.entries.len() as u64,
            window: SIGNED_WINDOW_BLOCKS,
        }
    }
}

/// "Your key was on N of the last M blocks", for the role card.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct SignedRecent {
    pub signed: u64,
    /// Blocks actually examined; `signed` is out of this, not out of `window`.
    pub seen: u64,
    pub window: u64,
}

/// Bring the window up to `tip` from the node, reading at most `budget`
/// heights this call (two RPCs each: `getblockhash`, `getmatmulattestations`).
///
/// A failed read leaves that height unrecorded and stops the pass; the next
/// call picks it up. Never an error: a window that is short of a few blocks is
/// still a true statement about the blocks it holds.
pub async fn refresh_recent_signers(
    rpc: &dyn Rpc,
    window: &mut RecentSigners,
    tip: u64,
    budget: usize,
) {
    for h in window.heights_to_read(tip, budget) {
        let Ok(v) = rpc.call("getblockhash", serde_json::json!([h])).await else {
            return;
        };
        let Some(hash) = v.as_str().map(str::to_string) else {
            return;
        };
        let Ok(a) = rpc
            .call("getmatmulattestations", serde_json::json!([hash]))
            .await
        else {
            return;
        };
        let atts: Vec<String> = a
            .as_array()
            .map(|xs| {
                xs.iter()
                    .filter_map(|x| x.as_str().map(str::to_string))
                    .collect()
            })
            .unwrap_or_default();
        window.record(h, &hash, &atts);
    }
}

