//! The signer role: a node that validates blocks signs a confirmation for each
//! one, so the mirrors that cannot validate can follow it.
//!
//! ── WHY THIS EXISTS ─────────────────────────────────────────────────────────
//! btxscan.io's explorer runs on a trusted mirror. It cannot replay the MatMul
//! proof itself, so it accepts a block only once a key it pins has signed it.
//! Four keys are pinned there. One of them signs. It lives on an RTX 3060 in a
//! home. On 2026-09-16 at 15:23Z that machine was switched off and the mirror
//! froze at 221,448 while the network went on to 221,464 and past; a test
//! transaction sent through the frozen mirror was relayed and mined five
//! minutes later, so money moved and the explorer and both wallets could not
//! see it. Seventeen archive nodes helped nothing: they serve signatures and
//! cannot make them. The engine prints the diagnosis on every start:
//! "single-key trusted mirror ... configure a second independent signer".
//!
//! 0.6.23 solved the archive half (every GPU-less PC serves history as a
//! keyless mirror). The signer half had no path through the app at all: the
//! one signer was configured by hand, in a conf file, once.
//!
//! ── WHAT THIS DOES ──────────────────────────────────────────────────────────
//! On a node that validates in consensus mode, the app keeps ONE signing key in
//! the datadir, `attestation-signer.key`, and hands its path to the engine as
//! `matmulattestationsignerkeyfile`. The engine adds the corresponding public
//! key to its signer set and signs an attestation for every block it validates
//! (`getmatmultrustedstatus.local_signer = true`). The key is generated here,
//! once, the first time signing is on: measured against the shipped 0.34.6
//! engine on 2026-09-16, a MISSING key file is fatal at init ("Error: Cannot
//! read MatMul attestation signing key file"), so the engine does not make one
//! and the app has to.
//!
//! The file holds one WIF-encoded secp256k1 secret, exactly what the engine's
//! `-matmulattestationsignerkeyfile` help asks for: "a file containing exactly
//! one WIF signing key". The WIF version byte is BTX's own, 0x99, read from the
//! key this project's validator has signed with since 2026-09-01 (its WIF
//! begins with `P`; Bitcoin's 0x80 would begin with `K` or `L`), and verified
//! the way that counts: a key generated by this module, handed to the shipped
//! engine, reports `local_signer: true` and lists its public key in
//! `trusted_signer_pubkeys` (the test at the bottom of `node.rs` runs that
//! against a real btxd when one is present).
//!
//! ── WHAT THE OPERATOR IS BEING ASKED FOR ────────────────────────────────────
//! Trust, not bandwidth. At threshold one a pinned key is a full authority: a
//! mirror that pins this node's key takes its word for the proof of work and
//! never checks. So the public key is shown, with a copy button, and the copy
//! next to it says that out loud. The private key never leaves the datadir and
//! is never shown; the public key is public by construction, since every
//! attestation on the network carries it.
//!
//! A signature only helps a mirror that HEARS it. Attestations travel to
//! connected peers, and a node relays only the keys it pins, so a volunteer's
//! signature reaches the explorer's mirror only over a direct connection. A
//! signer therefore dials the mirrors this project feeds
//! ([`BTX_MIRRORS_FED_BY_SIGNERS`]) as manual peers, so the operator needs no
//! port forwarding and the mirror's admin needs exactly one line: the pin.
//!
//! ── "IS IT WORKING?" ────────────────────────────────────────────────────────
//! A key that signs nothing looks exactly like one that signs everything, from
//! the outside (2026-09-03: a key pinned in good faith on a mirror produced
//! nothing for eleven days). So the role card reads the node's own stored
//! attestations for the last [`SIGNED_WINDOW_BLOCKS`] blocks and says how many
//! carry this node's key. [`RecentSigners`] is that window, pure and tested;
//! [`refresh_recent_signers`] feeds it from RPC incrementally, so a running
//! node pays two calls per new block rather than two hundred per tick.

